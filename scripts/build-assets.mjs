// Bundles the site's pages and media into assets.gen.js so the Worker can serve
// them itself. Runs automatically before `wrangler deploy` / `wrangler dev`
// (see [build] in wrangler.toml). The full-size stat_tracker_logo.png is left out:
// pages use the small stat_tracker_logo-sm.png, and Workers have a size limit.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const TEXT = ['.html', '.js'];
const BINARY = ['.png', '.mp4'];
const SKIP = new Set(['worker.js', 'assets.gen.js', 'stat_tracker_logo.png']);

const files = readdirSync('.').filter(f => !SKIP.has(f) && [...TEXT, ...BINARY].some(e => f.endsWith(e))).sort();
let out = '// Generated by scripts/build-assets.mjs. Do not edit.\n';
out += 'const b64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));\n';
out += 'export default {\n';
for (const f of files) {
  if (TEXT.some(e => f.endsWith(e))) out += `  ${JSON.stringify('/' + f)}: { text: ${JSON.stringify(readFileSync(f, 'utf8'))} },\n`;
  else out += `  ${JSON.stringify('/' + f)}: { bytes: b64(${JSON.stringify(readFileSync(f).toString('base64'))}) },\n`;
}
out += '};\n';
writeFileSync('assets.gen.js', out);
console.log(`bundled ${files.length} site files: ${files.join(', ')}`);
